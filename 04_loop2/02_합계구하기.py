"""
# While 실습 문제

파일명 : `02_합계구하기.py`

사용자가 입력한 숫자들을 계속 더해서 종료 시 `합계`와 `평균`을 출력하는 프로그램을 구현하세요
단, 사용자가 `0`을 입력하면 종료되며 0은 입력으로 간주하지 않습니다

```
숫자 입력 : (10)
숫자 입력 : (20)
숫자 입력 : (30)
숫자 입력 : (0)

합계 : 60
평균 : 20
```
"""


while True:
    number = int(input("숫자 입력 : "))

    if number == 0:
        break

print(f"합계 = ?")
print(f"평균 = ?")









