"""
# 실습 문제 : 베스킨라빈스 31

파일명 : `03_베스킨라빈스.py`

다음 규칙에 맞는 베스킨라빈스 게임을 구현하세요

- 사용자 두 명이 하나의 컴퓨터에서 하는 게임입니다.
- 사용자는 `1` ~ `3` 사이의 숫자만 입력이 가능합니다.
- 입력이 잘못된 경우 다시 입력을 받습니다.
- 숫자는 1부터 시작합니다.
- 사용자가 입력한 숫자만큼 숫자를 선택합니다.
  - 사용자가 `1`을 입력하면 1개의 숫자를 선택한다는 의미입니다. (1)
  - 사용자가 `2`을 입력하면 2개의 숫자를 선택한다는 의미입니다. (1, 2)
  - 사용자가 `3`을 입력하면 3개의 숫자를 선택한다는 의미입니다. (1, 2, 3)

31을 선택하는 사람이 지는 게임입니다.

```
베스킨 라빈스 게임 시작!
[현재 : 1] 숫자 1~3개 선택 : (1)
[현재 : 2] 숫자 1~3개 선택 : (2)
[현재 : 4] 숫자 1~3개 선택 : (3)
[현재 : 7] 숫자 1~3개 선택 : ...
...(중간 생략)...
[현재 : 29] 숫자 1~3개 선택 : (2)
[현재 : 31] 숫자 1~3개 선택 : (1)
31을 선택하여 게임이 종료되었습니다.
```

* 다 하신 분들은 컴퓨터는 랜덤으로 1~3을 고르게 해서 번갈아 진행하도록 업그레이드 해보세요
"""

now = 1

while True:
    text = f"[현재 {now}] 숫자 1~3개 선택 : "
    choice = int(input(text))

    # 나가는 시점 : 31을 골랐을 때
    # - now와 choice로 계산 전에 파악
    # - now를 계산한 뒤 파악

    # 더하기 전에 한다면...
    # if now + choice > 31:
    #     break

    now += choice

    # 더한 후에 한다면...
    if now > 31:
        break











